import {test} from 'node:test';
import assert from 'node:assert/strict';
import {Worker} from 'near-workspaces';

const ONE=10n**24n, GAS=250_000_000_000_000n;
const wasm='contract/target/near/agentledger_treasury.wasm';
test('sandbox: treasury authorization, accounting, callback receipts and replay protection', {timeout:240000}, async()=>{
 // Never allow NEAR_WORKSPACES_NETWORK to redirect these transactions to a public network.
 const worker=await Worker.init({network:'sandbox',rm:true});
 try {
  const root=worker.rootAccount;
  const owner=await root.createSubAccount('owner');
  const operator=await root.createSubAccount('operator');
  const vendor=await root.createSubAccount('vendor');
  const stranger=await root.createSubAccount('stranger');
  const treasury=await root.devDeploy(wasm);
  const expiry_ns=(BigInt(Date.now()+86400000)*1000000n).toString();
  const request=id=>treasury.view('get_request',{request_id:id});
  const liabilities=()=>treasury.view('get_liabilities');
  await assert.rejects(owner.call(treasury,'new',{owner:owner.accountId,operator:operator.accountId}),/initializer must be contract account/);
  await treasury.call(treasury,'new',{owner:owner.accountId,operator:operator.accountId});
  assert.deepEqual(await treasury.view('get_roles'),[owner.accountId,operator.accountId]);
  await assert.rejects(stranger.call(treasury,'set_vendor',{vendor:vendor.accountId,allowed:true}),/owner only/);
  await owner.call(treasury,'set_vendor',{vendor:vendor.accountId,allowed:true});
  assert.equal(await treasury.view('is_vendor_allowed',{vendor:vendor.accountId}),true);
  await assert.rejects(owner.call(treasury,'create_request',{request_id:'expired',expiry_ns:'1'},{attachedDeposit:ONE}),/expired/);
  await assert.rejects(owner.call(treasury,'create_request',{request_id:'empty',expiry_ns}),/deposit required/);
  await assert.rejects(stranger.call(treasury,'create_request',{request_id:'unauthorized',expiry_ns},{attachedDeposit:ONE}),/owner only/);
  const treasuryBefore=BigInt((await treasury.balance()).total);
  await owner.call(treasury,'create_request',{request_id:'success',expiry_ns},{attachedDeposit:ONE});
  assert(BigInt((await treasury.balance()).total)>=treasuryBefore+ONE);
  assert.equal(await liabilities(),String(ONE));
  assert.equal((await request('success')).status,'Funded');
  const auth=(payment_id,account=vendor.accountId,amount=ONE/2n)=>({request_id:'success',payment_id,vendor:account,amount:String(amount)});
  await assert.rejects(stranger.call(treasury,'authorize',auth('bad-owner')),/owner only/);
  await assert.rejects(owner.call(treasury,'authorize',auth('bad-vendor',stranger.accountId)),/vendor not allowed/);
  await assert.rejects(owner.call(treasury,'authorize',auth('too-much',vendor.accountId,ONE+1n)),/budget exceeded/);
  await owner.call(treasury,'authorize',auth('p-success'));
  assert.equal((await request('success')).status,'Authorized');
  assert.equal(await treasury.view('get_payment_request',{payment_id:'p-success'}),'success');
  await assert.rejects(stranger.call(treasury,'execute',{request_id:'success'},{gas:GAS}),/unauthorized/);
  await assert.rejects(stranger.call(treasury,'refund',{request_id:'success'},{gas:GAS}),/owner only/);
  const vendorBefore=BigInt((await vendor.balance()).total);
  const execution=await operator.callRaw(treasury,'execute',{request_id:'success'},{gas:GAS});
  assert.equal(execution.parseResult(),true);
  assert.equal(execution.receiptFailures.length,0);
  assert(execution.receiptSuccessValues.includes(Buffer.from('true').toString('base64')));
  assert.equal(BigInt((await vendor.balance()).total)-vendorBefore,ONE/2n);
  assert.equal((await request('success')).status,'Completed');
  assert.equal((await request('success')).remaining,String(ONE/2n));
  assert.equal(await liabilities(),String(ONE/2n));
  await assert.rejects(operator.call(treasury,'execute',{request_id:'success'},{gas:GAS}),/invalid status/);
  const refund=await owner.callRaw(treasury,'refund',{request_id:'success'},{gas:GAS});
  assert.equal(refund.parseResult(),true);
  assert.equal(refund.receiptFailures.length,0);
  assert(refund.receiptSuccessValues.includes(Buffer.from('true').toString('base64')));
  assert.equal((await request('success')).status,'Refunded');
  assert.equal((await request('success')).remaining,'0');
  assert.equal(await liabilities(),'0');
  await assert.rejects(owner.call(treasury,'refund',{request_id:'success'},{gas:GAS}),/invalid status/);
  await owner.call(treasury,'create_request',{request_id:'duplicate',expiry_ns},{attachedDeposit:ONE});
  await assert.rejects(owner.call(treasury,'authorize',{request_id:'duplicate',payment_id:'p-success',vendor:vendor.accountId,amount:String(ONE/2n)}),/duplicate payment id/);
  assert.equal((await request('duplicate')).status,'Funded');
  await owner.call(treasury,'refund',{request_id:'duplicate'},{gas:GAS});
  assert.equal(await liabilities(),'0');
  const missing=`missing.${root.accountId}`;
  await owner.call(treasury,'set_vendor',{vendor:missing,allowed:true});
  await owner.call(treasury,'create_request',{request_id:'failure',expiry_ns},{attachedDeposit:ONE});
  await owner.call(treasury,'authorize',{request_id:'failure',payment_id:'p-failure',vendor:missing,amount:String(ONE/2n)});
  const failed=await operator.callRaw(treasury,'execute',{request_id:'failure'},{gas:GAS});
  assert.equal(failed.parseResult(),false);
  assert(failed.receiptFailures.length>=1);
  assert(failed.receiptSuccessValues.includes(Buffer.from('false').toString('base64')));
  assert.equal((await request('failure')).status,'Failed');
  assert.equal((await request('failure')).remaining,String(ONE));
  assert.equal(await liabilities(),String(ONE));
  await assert.rejects(operator.call(treasury,'execute',{request_id:'failure'},{gas:GAS}),/invalid status/);
  const recovered=await owner.callRaw(treasury,'refund',{request_id:'failure'},{gas:GAS});
  assert.equal(recovered.parseResult(),true);
  assert.equal(recovered.receiptFailures.length,0);
  assert.equal((await request('failure')).status,'Refunded');
  assert.equal((await request('failure')).remaining,'0');
  assert.equal(await liabilities(),'0');
 } finally {await worker.tearDown();}
});
